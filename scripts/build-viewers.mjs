import { build } from 'esbuild';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../', import.meta.url));
const check = process.argv.includes('--check');
if (process.argv.slice(2).some(arg => arg !== '--check')) throw new Error('Only --check is supported');
const aliases = new Map([['./jxl/decode.js', 'node_modules/@jsquash/jxl/decode.js'], ['./jxl-header.js', 'src/shared/jxl-header.js']]);
for (const [name, entry] of [['pdf', 'node_modules/pdfjs-dist/build/pdf.worker.mjs'], ['jxl', 'src/document-viewer/jxl-worker.js']]) {
  const outfile = path.join(root, `src/document-viewer/generated/${name}.worker.js`);
  const result = await build({ absWorkingDir: root, entryPoints: [entry], outfile, bundle: true, format: 'iife', platform: 'browser', target: 'chrome152',
    minify: true, sourcemap: false, legalComments: 'eof', charset: 'ascii', write: !check, logLevel: 'silent',
    define: { 'import.meta.url': JSON.stringify('ord://document-viewer/assets/decoder.js') },
    banner: { js: `// Generated by npm run build:viewers. Do not edit. ${name.toUpperCase()} decoder; upstream licenses retained below.` },
    plugins: [{ name: 'fixed-viewer-imports', setup(build) {
      build.onResolve({ filter: /^\.\/(?:jxl\/decode|jxl-header)\.js$/ }, args => {
        if (args.importer !== path.join(root, 'src/document-viewer/jxl-worker.js')) return null;
        return { path: path.join(root, aliases.get(args.path)) };
      });
    } }]
  });
  if (check) {
    const actual = await fs.readFile(outfile);
    if (!actual.equals(Buffer.from(result.outputFiles[0].contents))) throw new Error(`The ${name} worker is stale. Run npm run build:viewers.`);
  }
  console.log(`${check ? 'Verified' : 'Built'} local classic ${name.toUpperCase()} worker`);
}
