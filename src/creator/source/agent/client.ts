import net from 'node:net';
import {readFile,lstat} from 'node:fs/promises';
import {z} from 'zod';
import {AppError} from '../core/errors';
import {validate} from '../core/validation';
import type {AgentConnection} from './bridge';

export async function readConnection(filename:string):Promise<AgentConnection>{
  const stat=await lstat(filename);
  if(!stat.isFile()||stat.isSymbolicLink()||stat.size>4096)throw new AppError('INVALID_CONNECTION','Use the connection file generated by Bitcoin Website Builder.');
  if(process.platform!=='win32'&&(stat.mode&0o077))throw new AppError('PRIVATE_CONNECTION_REQUIRED','The AI connection file must be readable only by its owner.');
  return validate(z.object({schemaVersion:z.literal(1),endpoint:z.string().min(1).max(512),token:z.string().min(40).max(64),grantId:z.string().uuid()}).strict(),JSON.parse(await readFile(filename,'utf8')));
}
export class BridgeClient {
  constructor(private config:AgentConnection){}
  call(command:string,payload:unknown,signal?:AbortSignal):Promise<any>{
    return new Promise((resolve,reject)=>{
      if(signal?.aborted){reject(new AppError('CANCELED','Operation canceled before it started.'));return;}
      const socket=net.createConnection(this.config.endpoint);let data=Buffer.alloc(0),done=false;
      const finish=(error?:Error,result?:unknown)=>{if(done)return;done=true;signal?.removeEventListener('abort',cancel);socket.destroy();error?reject(error):resolve(result);};
      const cancel=()=>finish(new AppError('CANCELED','Request canceled. A submitted atomic edit may have finished; inspect the project before retrying.'));
      signal?.addEventListener('abort',cancel,{once:true});
      socket.setTimeout(90_000,()=>finish(new AppError('TIMEOUT','The app did not respond. Inspect its state before retrying a mutation.')));
      socket.once('connect',()=>socket.write(JSON.stringify({token:this.config.token,grantId:this.config.grantId,command,payload})+'\n'));
      socket.on('data',chunk=>{data=Buffer.concat([data,Buffer.from(chunk)]);if(data.length>12_000_000)finish(new AppError('RESULT_TOO_LARGE','Read a smaller result range.'));});
      socket.once('end',()=>{try{finish(undefined,JSON.parse(data.toString('utf8')));}catch{finish(new AppError('INVALID_RESPONSE','The app returned an incomplete response.'));}});
      socket.once('error',()=>finish(new AppError('APP_UNAVAILABLE','Open Bitcoin Website Builder and reconnect this AI connection.')));
      socket.once('close',()=>{if(!done)finish(new AppError('CONNECTION_CLOSED','The app connection closed. Inspect current project state before retrying.'));});
    });
  }
}
